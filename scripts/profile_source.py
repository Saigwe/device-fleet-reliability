"""Profile the bronze source table and write docs/data_profile.md (part of the data catalogue).

Uses DuckDB's SUMMARIZE: per column type, min, max, approximate distinct count, null percentage.
Also records rows, days, drives and the date range, so a reviewer sees what was loaded without
querying the warehouse.

Usage
    python scripts/profile_source.py --db warehouse/fleet.duckdb
"""
from __future__ import annotations

import argparse
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", default="warehouse/fleet.duckdb")
    ap.add_argument("--out", default=str(ROOT / "docs" / "data_profile.md"))
    args = ap.parse_args()

    with duckdb.connect(args.db, read_only=True) as con:
        prof = con.execute("summarize bronze.drive_days").df()
        rows, days, drives, first, last = con.execute("""
            select count(*), count(distinct date), count(distinct serial_number), min(date), max(date)
            from bronze.drive_days""").fetchone()

    prof = prof[["column_name", "column_type", "min", "max", "approx_unique", "null_percentage"]]
    prof["min"] = prof["min"].astype(str).str.slice(0, 24)
    prof["max"] = prof["max"].astype(str).str.slice(0, 24)
    lines = [
        "# Source profile: bronze.drive_days",
        "",
        f"{rows:,} rows · {days} days ({first} to {last}) · {drives:,} distinct drives. "
        "Generated by `scripts/profile_source.py`.",
        "",
        "Ownership and classification metadata live in the dbt YAML (`meta`), and lineage in "
        "`dbt docs generate` / `dbt docs serve`.",
        "",
        prof.to_markdown(index=False),
    ]
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
